"""Базовый класс обработчика."""


class Handler:
    """Обработчик возвращает True, если событие его, и остальные уже не вызываются.

    drafts — хранилище черновиков диалога (если у обработчика есть многошаговый диалог).
    Роутер использует его, чтобы у человека был открыт только один черновик за раз.
    """

    drafts = None

    def on_message(self, ctx) -> bool:
        return False

    def on_callback(self, ctx) -> bool:
        return False
